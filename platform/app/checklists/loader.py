"""Checklist templates (DESIGN.md §4.11). Reviewed YAML, filled in deterministically.

Never generated by AI. A template is chosen by incident kind and host type:
    templates/<kind>/<host_type>.yaml, falling back to templates/<kind>/default.yaml
"""

import string
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import yaml

TEMPLATES_DIR = Path(__file__).resolve().parent / "templates"
KINDS = ("manual", "auto")
# Every placeholder a template may use. Values are filled from the case, never from AI.
PLACEHOLDERS = frozenset(
    {"component", "current_version", "fix_text", "advisory_ids", "host", "edge_status"}
)


class TemplateError(ValueError):
    pass


@dataclass(frozen=True)
class TemplateItem:
    key: str
    kind: str
    text: str


@dataclass(frozen=True)
class ChecklistTemplate:
    key: str  # e.g. "php-core/managed-wp"
    title: str
    items: tuple[TemplateItem, ...]


@dataclass(frozen=True)
class RenderedItem:
    key: str
    kind: str
    text: str


def _placeholders(text: str) -> set[str]:
    return {name for _, name, _, _ in string.Formatter().parse(text) if name}


@lru_cache
def load(path: Path) -> ChecklistTemplate:
    data = yaml.safe_load(path.read_text())
    key = f"{path.parent.name}/{path.stem}"
    if not isinstance(data, dict) or not isinstance(data.get("items"), list):
        raise TemplateError(f"{key}: needs a title and a list of items")
    items, seen = [], set()
    for raw in data["items"]:
        item = TemplateItem(str(raw["key"]), str(raw["kind"]), str(raw["text"]))
        if item.key in seen:
            raise TemplateError(f"{key}: duplicate item key {item.key!r}")
        if item.kind not in KINDS:
            raise TemplateError(f"{key}: item {item.key!r} has unknown kind {item.kind!r}")
        unknown = _placeholders(item.text) - PLACEHOLDERS
        if unknown:
            raise TemplateError(f"{key}: item {item.key!r} uses unknown placeholders {unknown}")
        seen.add(item.key)
        items.append(item)
    return ChecklistTemplate(key, str(data.get("title", key)), tuple(items))


def all_templates() -> list[ChecklistTemplate]:
    return [load(p) for p in sorted(TEMPLATES_DIR.glob("*/*.yaml"))]


def template_for(incident_kind: str, host_type: str) -> ChecklistTemplate:
    for name in (host_type, "default"):
        path = TEMPLATES_DIR / incident_kind / f"{name}.yaml"
        if path.is_file():
            return load(path)
    return load(TEMPLATES_DIR / "lib" / "default.yaml")


def render(template: ChecklistTemplate, values: dict[str, str]) -> list[RenderedItem]:
    filled = {name: values.get(name) or "?" for name in PLACEHOLDERS}
    return [RenderedItem(i.key, i.kind, i.text.format_map(filled)) for i in template.items]
